const assert=require("node:assert/strict"),a=require("./robinhood-adapter.cjs");
const now=Date.parse("2026-10-13T14:00:00Z");
const bar=t=>({begins_at:t,open_price:"100",close_price:"101",high_price:"102",low_price:"99",volume:10,session:"reg",interpolated:false});
const response=bars=>({data:{results:[{symbol:"TEST",interval:"5minute",bounds:"regular",bars}]}});
const five=a.historical(response([bar("2026-10-13T13:30:00Z"),bar("2026-10-13T13:35:00Z"),bar("2026-10-13T13:40:00Z")]),"TEST","5minute",now);
assert.equal(five[0].closedAt,"2026-10-13T13:35:00.000Z");
assert.equal(a.fifteen(five)[0].closedAt,"2026-10-13T13:45:00.000Z");
assert.equal(a.fifteen(five)[0].volume,30);
assert.equal(a.fifteen(five.slice(1)).length,0);
assert.equal(a.historical(response([bar("2026-10-13T14:00:00Z")]),"TEST","5minute",now).length,0);
assert.equal(a.historical(response([{...bar("2026-10-13T13:30:00Z"),interpolated:true}]),"TEST","5minute",now).length,0);
assert.equal(new Date(a.wallUTC("2026-10-13",16)).toISOString(),"2026-10-13T20:00:00.000Z");
assert.equal(new Date(a.wallUTC("2026-12-01",16)).toISOString(),"2026-12-01T21:00:00.000Z");
const q={data:{results:[{quote:{symbol:"TEST",state:"active",has_traded:true,last_trade_price:"101",venue_last_trade_time:"2026-10-13T13:59:30Z"}}]}};
assert.equal(a.quote(q,"TEST").coverage,"unknown");
assert.equal(a.quote(q,"TEST",{coverage:"consolidated",coverageEvidence:"Verified feed metadata"}).coverage,"consolidated");
assert.equal(a.quote(q,"TEST").at,"2026-10-13T13:59:30Z");
assert.throws(()=>a.payload({isError:true}),/error/);
assert.throws(()=>a.quote(q,"MISSING"),/unavailable/);
assert.throws(()=>a.historical(response([]),"MISSING","5minute",now),/Missing/);
console.log("Robinhood timestamp, DST, aggregation, incomplete-bar and coverage checks passed.");
